    def unload(self):
        """Limpa os recursos do plugin ao ser desativado."""

        # --- NOVO: Remove o atalho do Gerenciador do QGIS ---
        if hasattr(self, 'action') and self.action:
            self.iface.unregisterMainWindowAction(self.action)
        # ----------------------------------------------------
        
        # 1. Limpa as camadas de preview da memória
        self.limpar_clones_preview()

        # Desconecta os filtros da combo para não dar erro de runtime
        try:
            QgsProject.instance().layersAdded.disconnect(self._filtrar_camadas_da_combo)
            QgsProject.instance().layersRemoved.disconnect(self._filtrar_camadas_da_combo)
        except: pass

        # 2. Remove as ações dos menus e barras
        for action in self.actions:
            self.iface.removePluginMenu(self.menu, action)
            self.iface.removeToolBarIcon(action)
        
        # 3. Limpeza segura da Toolbar (Foco QGIS 4.0 e Plugin Reloader)
        if hasattr(self, 'toolbar') and self.toolbar:
            if not sip.isdeleted(self.toolbar):
                self.iface.mainWindow().removeToolBar(self.toolbar)
                self.toolbar.hide() # Esconde fisicamente na hora
                self.toolbar.setParent(None) # Pulo do Gato: Desvincula do QGIS instantaneamente
                self.toolbar.deleteLater() # Agenda a deleção segura na memória
            del self.toolbar

        # 4. Limpeza segura do Diálogo
        if hasattr(self, 'dlg') and self.dlg:
            if not sip.isdeleted(self.dlg):
                self.dlg.close()
                self.dlg.setParent(None) # Desvincula da memória principal
                self.dlg.deleteLater()
            del self.dlg

        # 5. Coleta de lixo final
        gc.collect()

    
    
    
